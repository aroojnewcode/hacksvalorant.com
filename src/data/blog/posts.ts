function readTimeFromBody(post: BlogPostFull): string {
  const parts: string[] = [post.desc];
  for (const block of post.body) {
    if ('text' in block && block.text) parts.push(block.text);
    if ('title' in block && block.title) parts.push(block.title);
    if ('items' in block) parts.push(...block.items);
    if ('headers' in block) parts.push(...block.headers);
    if ('rows' in block) parts.push(...block.rows.flat());
  }
  const words = parts.join(' ').split(/\s+/).filter(Boolean).length;
  const minutes = Math.max(1, Math.ceil(words / 200));
  return `${minutes} min read`;
}

