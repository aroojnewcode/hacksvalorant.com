import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { REDIRECT_301 } from '../src/config/redirect-map.mjs';
import { VALORANT_CHECKOUT_URL } from '../src/config/checkout-redirects.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'public', '_redirects');

const checkout302 = [
  '/go/mw4',
  '/go/mw4/',
  '/go/borderlands',
  '/go/borderlands/',
  '/go/bodycam',
  '/go/bodycam/',
  '/go/fortnite',
  '/go/fortnite/',
  '/go/skin-changer',
  '/go/skin-changer/',
  '/go/hwid-spoofer',
  '/go/hwid-spoofer/',
  '/go/ugc',
  '/go/ugc/',
];

const lines = [
  '# Generated by scripts/write-redirects.mjs — edit redirect-map.mjs instead.',
  '# Apex host. The worker also forces https://hacksvalorant.com.',
  'http://hacksvalorant.com/*  https://hacksvalorant.com/:splat  301',
  'http://www.hacksvalorant.com/*  https://hacksvalorant.com/:splat  301',
  'https://www.hacksvalorant.com/*  https://hacksvalorant.com/:splat  301',
  '',
  '# Checkout (302 → Zadeyo; /go/valorant/ is SSR bridge, not listed here)',
  ...checkout302.map((from) => `${from}  ${VALORANT_CHECKOUT_URL}  302`),
  '',
  '# 301 legacy → final URL (single hop map, worker resolves chains)',
  ...[...REDIRECT_301.entries()]
    .filter(([from, to]) => from !== to)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([from, to]) => `${from}  ${to}  301`),
  '',
];

fs.writeFileSync(out, `${lines.join('\n')}\n`, 'utf8');
console.log(`write-redirects: ${REDIRECT_301.size} 301 rules → public/_redirects`);
